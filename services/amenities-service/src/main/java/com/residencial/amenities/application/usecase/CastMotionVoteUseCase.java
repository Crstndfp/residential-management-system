package com.residencial.amenities.application.usecase;

import com.residencial.amenities.application.dto.CastVoteRequest;
import com.residencial.amenities.application.dto.VoteResponse;
import com.residencial.amenities.domain.exception.DuplicateVoteException;
import com.residencial.amenities.domain.exception.MotionNotFoundException;
import com.residencial.amenities.domain.exception.MotionNotOpenException;
import com.residencial.amenities.domain.exception.TenantVotingForbiddenException;
import com.residencial.amenities.domain.model.AssemblyMotion;
import com.residencial.amenities.domain.model.MotionStatus;
import com.residencial.amenities.domain.model.MotionVote;
import com.residencial.amenities.domain.model.VoteChoice;
import com.residencial.amenities.domain.repository.AssemblyMotionRepository;
import com.residencial.amenities.domain.repository.MotionVoteRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.util.UUID;

@Service
public class CastMotionVoteUseCase {

    private final AssemblyMotionRepository motionRepository;
    private final MotionVoteRepository voteRepository;

    public CastMotionVoteUseCase(AssemblyMotionRepository motionRepository,
                                 MotionVoteRepository voteRepository) {
        this.motionRepository = motionRepository;
        this.voteRepository = voteRepository;
    }

    @Transactional
    public VoteResponse execute(UUID motionId, CastVoteRequest request, String userRole) {
        // Invariant 1: Only OWNER role can cast a vote
        if (userRole == null || !"OWNER".equalsIgnoreCase(userRole.trim())) {
            throw new TenantVotingForbiddenException(userRole != null ? userRole : "ANONYMOUS");
        }

        // Invariant 2: Motion must exist and be OPEN
        AssemblyMotion motion = motionRepository.findById(motionId)
                .orElseThrow(() -> new MotionNotFoundException(motionId));

        if (motion.getStatus() != MotionStatus.OPEN) {
            throw new MotionNotOpenException(motionId, motion.getStatus());
        }

        // Invariant 3: Exactly 1 vote per house per motion
        if (voteRepository.existsByMotionIdAndHouseId(motionId, request.houseId())) {
            throw new DuplicateVoteException(motionId, request.houseId());
        }

        VoteChoice choice = VoteChoice.valueOf(request.voteChoice().toUpperCase().trim());

        MotionVote vote = new MotionVote(
                UUID.randomUUID(),
                motionId,
                request.houseId(),
                request.houseNumber(),
                request.voterUserId(),
                choice,
                null, // will be auto-generated by constructor using SHA-256
                Instant.now()
        );

        MotionVote saved = voteRepository.save(vote);
        return VoteResponse.fromDomain(saved);
    }
}
